"""Migration tests.

The tests build their schema with `create_all`; real databases are built by
migrations. That is a shortcut worth taking — but only if the two agree, and
nothing enforces agreement by itself. A column added to `db/models.py` without a
matching migration passes every other test in this suite and then fails on the
one database that has data in it.

So this file is the guard on that shortcut. It is also the guard on Phase 4 and
Phase 5, both of which add tables.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest
from sqlalchemy import create_engine, inspect

from db.models import Base

PROJECT_ROOT = Path(__file__).resolve().parent.parent


def run_alembic(*args: str, db_url: str) -> subprocess.CompletedProcess:
    """Drive Alembic as a subprocess.

    In-process would be faster, but Alembic's `env.py` reads `DB_PATH` at import
    and runs its own event loop — exercising it the way it is actually invoked
    avoids testing a configuration nobody uses.
    """
    return subprocess.run(
        [sys.executable, "-m", "alembic", *args],
        cwd=PROJECT_ROOT,
        env={"PATH": "/usr/bin:/bin", "DB_PATH": db_url, "HOME": str(Path.home())},
        capture_output=True,
        text=True,
    )


@pytest.fixture
def migrated_db(tmp_path):
    """A real on-disk database built by running the migrations."""
    db_file = tmp_path / "migrated.db"
    result = run_alembic("upgrade", "head", db_url=f"sqlite+aiosqlite:///{db_file}")
    assert result.returncode == 0, result.stderr
    return db_file


def test_migrations_produce_the_schema_the_models_describe(migrated_db):
    """The check that makes `create_all` in the test fixtures safe.

    `alembic check` autogenerates against the live database and fails if it
    finds anything to do — so a model change without a migration is caught here
    rather than on the database that holds real data.
    """
    result = run_alembic("check", db_url=f"sqlite+aiosqlite:///{migrated_db}")

    assert result.returncode == 0, (
        "Models and migrations disagree. Run:\n"
        "  python -m alembic revision --autogenerate -m 'describe the change'\n\n"
        f"{result.stdout}\n{result.stderr}"
    )


def test_every_model_table_exists_after_migrating(migrated_db):
    """A blunt cross-check on `alembic check`, which is itself autogenerated
    logic — if it ever silently no-ops, this still catches a missing table."""
    engine = create_engine(f"sqlite:///{migrated_db}")
    actual = set(inspect(engine).get_table_names())
    engine.dispose()

    expected = set(Base.metadata.tables)
    assert expected <= actual, f"missing tables: {expected - actual}"


def test_migrations_are_reversible(migrated_db):
    """A migration that cannot be undone is a one-way door.

    SQLite cannot drop or alter columns in place, so a downgrade only works if
    the migration was rendered in batch mode. This asserts that stayed on.
    """
    url = f"sqlite+aiosqlite:///{migrated_db}"
    result = run_alembic("downgrade", "base", db_url=url)
    assert result.returncode == 0, result.stderr

    engine = create_engine(f"sqlite:///{migrated_db}")
    remaining = set(inspect(engine).get_table_names())
    engine.dispose()

    # Alembic's own bookkeeping table is expected to survive.
    assert remaining == {"alembic_version"}, f"downgrade left behind: {remaining}"


def test_a_pre_alembic_database_is_refused_with_an_explanation(tmp_path):
    """The failure a real user hits first.

    A database from the old `create_all` has the tables but no
    `alembic_version`, so Alembic thinks it is empty, tries to create `ads`, and
    dies in a wall of SQL that names the symptom and not the cause.
    """
    import sqlite3

    from db.connection import UnmanagedDatabaseError, check_is_migratable

    legacy = tmp_path / "legacy.db"
    with sqlite3.connect(legacy) as conn:
        conn.execute("CREATE TABLE ads (id INTEGER PRIMARY KEY, blocket_id TEXT)")

    with pytest.raises(UnmanagedDatabaseError, match="predates"):
        check_is_migratable(f"sqlite+aiosqlite:///{legacy}")


def test_a_migrated_database_is_accepted(migrated_db):
    from db.connection import check_is_migratable

    check_is_migratable(f"sqlite+aiosqlite:///{migrated_db}")  # must not raise


def test_a_missing_database_is_fine(tmp_path):
    """First run on a clean checkout: nothing to guard against."""
    from db.connection import check_is_migratable

    check_is_migratable(f"sqlite+aiosqlite:///{tmp_path / 'does-not-exist.db'}")


def test_there_is_exactly_one_migration_head():
    """Two heads means two people (or two branches) added migrations in
    parallel and `upgrade head` no longer has a single answer."""
    result = run_alembic("heads", db_url="sqlite+aiosqlite:///:memory:")

    assert result.returncode == 0, result.stderr
    heads = [line for line in result.stdout.splitlines() if "(head)" in line]
    assert len(heads) == 1, f"expected one head, found {len(heads)}:\n{result.stdout}"
